// Console.h — всё, что зависит от операционной системы: кодировка, цвет,
// очистка экрана и чтение строки с клавиатуры.
// Ответственный: Новикова Полина (Интерфейс).
// Код с #ifdef _WIN32 должен быть только в Console.cpp.
#pragma once

#include <cstddef>

/// Цвета текста в консоли.
enum class ConsoleColor
{
    Default,
    Red,
    Green,
    Yellow,
    Blue,
    Magenta,
    Cyan,
    Gray
};

/// Результат чтения строки с клавиатуры.
enum class ReadStatus
{
    Ok,          ///< Строка прочитана целиком
    TooLong,     ///< Строка не поместилась в буфер: буфер пустой, остаток строки пропущен
    EndOfInput   ///< Ввод закрыт: Ctrl+D на Mac, Ctrl+Z и Enter на Windows
};

namespace Console
{
    /// Настраивает консоль: UTF-8 для вывода и ввода, проверяет, работают ли цвета.
    /// Вызывается один раз в начале main, до любого вывода.
    void initialize();

    /// Возвращает true, если цвета включены.
    /// Цвета выключаются сами, если консоль их не поддерживает, вывод
    /// перенаправлен в файл или задана переменная окружения NO_COLOR.
    bool isColorEnabled();

    /// Принудительно включает или выключает цвета (например, из настроек меню).
    /// Включить цвета можно, только если консоль их поддерживает.
    void setColorEnabled(bool enabled);

    /// Переключает цвет следующего текста. Ничего не делает, если цвета выключены.
    void setColor(ConsoleColor color);

    /// Возвращает обычный цвет текста.
    void resetColor();

    /// Печатает текст указанным цветом и возвращает обычный цвет.
    void printColored(const char* utf8Text, ConsoleColor color);

    /// Очищает экран. Без поддержки цветов просто сдвигает старый текст вверх.
    void clearScreen();

    /// Возвращает число видимых символов в строке UTF-8.
    /// strlen считает байты, а русская буква занимает 2 байта.
    std::size_t getDisplayWidth(const char* utf8Text);

    /// Печатает текст и дополняет его пробелами справа до ширины width
    /// видимых символов. Если текст длиннее, печатает его целиком.
    void printPadded(const char* utf8Text, std::size_t width);

    /// Читает одну строку с клавиатуры в кодировке UTF-8 (без '\n' и '\r').
    /// buffer — массив на capacity байт, строка всегда завершается '\0'.
    /// На Windows кириллица читается через UTF-16 и переводится в UTF-8,
    /// потому что обычный std::cin в консоли Windows её портит.
    ReadStatus readLine(char* buffer, std::size_t capacity);
}
